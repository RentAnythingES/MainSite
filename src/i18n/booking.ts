export function bookingText(
  locale: "en" | "es" | "de",
  en: string,
  es = en,
): string {
  if (locale === "de") {
    if (!supplements[en]) throw new Error(`Missing German booking text: ${en}`);
    return supplements[en];
  }
  return locale === "es" ? es : en;
}
